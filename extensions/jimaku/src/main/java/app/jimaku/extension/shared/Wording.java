    private Wording() {
    }

    /** The message for {@code key} in {@code locale}'s language, or English, with its placeholders filled. */
    public static String t(Locale locale, String key, String... substitutions) {
        Map<String, String> messages = MESSAGES.get(locale.getLanguage());
        String message = messages == null ? null : messages.get(key);
        if (message == null) message = MESSAGES.get("en").get(key);
        if (message == null) throw new IllegalArgumentException("No message " + key);
        StringBuilder text = new StringBuilder();
        for (int i = 0; i < message.length(); i++) {
            char c = message.charAt(i);
            if (c == '$' && i + 1 < message.length()) {
                char next = message.charAt(i + 1);
                if (next == '$') {
                    text.append('$');
                    i++;
                    continue;
                }
                if (next >= '1' && next <= '9') {
                    int index = next - '1';
                    text.append(index < substitutions.length ? substitutions[index] : "");
                    i++;
                    continue;
                }
            }
            text.append(c);
        }
        return text.toString();
    }

    /** {@link #t(Locale, String, String...)} in the app's language. */
    public static String t(String key, String... substitutions) {
        return t(Locale.getDefault(), key, substitutions);
    }

